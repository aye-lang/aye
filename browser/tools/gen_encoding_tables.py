#!/usr/bin/env python3
"""Generates browser/encoding/tables.aye from the WHATWG Encoding Standard's
index files (https://encoding.spec.whatwg.org/index-NAME.txt).

    python3 browser/tools/gen_encoding_tables.py DIR [OUT]

DIR holds index-jis0208.txt, index-jis0212.txt, index-iso-2022-jp-katakana.txt,
index-gb18030.txt, index-gb18030-ranges.txt, index-big5.txt and
index-euc-kr.txt (download them with `--fetch DIR` first). OUT defaults to
browser/encoding/tables.aye.

A big index is a dense table from its first to its last pointer: each
code point is WIDTH hex digits (0 for a pointer without one), 64 per line
of an Aye multi-line string, so the code point of a pointer is found by
its offset (`Index.at` in cjk.aye).
"""

import os
import sys
import urllib.request

NAMES = ["jis0208", "jis0212", "iso-2022-jp-katakana", "gb18030", "gb18030-ranges", "big5", "euc-kr"]
PER_LINE = 64


def read(path):
    entries = {}
    ident = ""
    date = ""
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("# Identifier:"):
                ident = line.split(":", 1)[1].strip()
            elif line.startswith("# Date:"):
                date = line.split(":", 1)[1].strip()
            if line.startswith("#") or not line.strip():
                continue
            pointer, code = line.split("\t")[:2]
            entries[int(pointer.strip())] = int(code, 16)
    return entries, ident, date


def dense(name, const, entries, width):
    start = min(entries)
    end = max(entries) + 1
    out = []
    out.append(f"pub let {const} = Index {{ start: {start}, len: {end - start}, width: {width}, hex: {const}_HEX }}\n")
    out.append(f"let {const}_HEX =\n")
    for lo in range(start, end, PER_LINE):
        row = "".join(f"{entries.get(p, 0):0{width}X}" for p in range(lo, min(lo + PER_LINE, end)))
        out.append(f"    \\\\{row}\n")
    out.append("\n")
    return "".join(out)


def array(const, ty, values):
    out = [f"pub let {const} = [{len(values)}]{ty}{{\n"]
    for lo in range(0, len(values), 12):
        out.append("    " + " ".join(f"0x{v:X}," for v in values[lo:lo + 12]) + "\n")
    out.append("}\n\n")
    return "".join(out)


def main():
    args = sys.argv[1:]
    if args and args[0] == "--fetch":
        os.makedirs(args[1], exist_ok=True)
        for n in NAMES:
            url = f"https://encoding.spec.whatwg.org/index-{n}.txt"
            with urllib.request.urlopen(url) as r, open(os.path.join(args[1], f"index-{n}.txt"), "wb") as f:
                f.write(r.read())
        return
    if not args:
        sys.exit(__doc__)
    src = args[0]
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    dst = args[1] if len(args) > 1 else os.path.join(root, "browser", "encoding", "tables.aye")
    idx = {n: read(os.path.join(src, f"index-{n}.txt")) for n in NAMES}
    out = []
    out.append("// The indexes of the WHATWG Encoding Standard that the CJK decoders and\n")
    out.append("// encoders use (cjk.aye). Generated by browser/tools/gen_encoding_tables.py\n")
    out.append("// from https://encoding.spec.whatwg.org/index-*.txt; do not edit.\n")
    out.append("//\n")
    for n in NAMES:
        out.append(f"// index-{n}.txt: {idx[n][2]}, {idx[n][1]}\n")
    out.append("\n")
    for n, const in [("jis0208", "JIS0208"), ("jis0212", "JIS0212"), ("gb18030", "GB18030"), ("euc-kr", "EUC_KR")]:
        entries = idx[n][0]
        assert max(entries.values()) <= 0xFFFF, n
        out.append(dense(n, const, entries, 4))
    # Big5 has code points in plane 2: five hex digits.
    out.append(dense("big5", "BIG5", idx["big5"][0], 5))
    kata = idx["iso-2022-jp-katakana"][0]
    out.append(array("ISO2022JP_KATAKANA", "u32", [kata[p] for p in range(len(kata))]))
    ranges = sorted(idx["gb18030-ranges"][0].items())
    out.append(array("GB18030_RANGE_POINTERS", "u32", [p for p, _ in ranges]))
    out.append(array("GB18030_RANGE_CODES", "u32", [c for _, c in ranges]).rstrip("\n") + "\n")
    with open(dst, "w", encoding="utf-8") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main()
